/* ---------- Progress bars (progress panel) ---------- */
function renderProgressBars() {
  const wrap = el("progressBars");
  if (!wrap) return;
  const rows = allProjects
    .map((p) => ({ p, prog: progressMap[p.id] || { percent: 0, status: "none" } }))
    .filter((r) => r.prog.percent > 0 || r.prog.status === "started")
    .sort((a, b) => b.prog.percent - a.prog.percent);

  if (!rows.length) {
    wrap.innerHTML = '<div class="dash-empty">Start projects to see your progress here.</div>';
    return;
  }
  wrap.innerHTML = rows.map((r) =>
    '<div class="progress-row">' +
      '<div class="progress-row-head"><b>' + escapeHtml(r.p.title) + "</b><span>" +
        (r.prog.status === "completed" ? "Completed" : r.prog.percent + "%") + "</span></div>" +
      '<div class="bar"><div class="bar-fill" style="width:' + r.prog.percent + '%"></div></div>' +
    "</div>"
  ).join("");
}

