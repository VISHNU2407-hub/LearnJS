async function init() {
  const user = await requireAuth("../dashboard/");
  currentUser = user;
  document.body.classList.add("authenticated");
  el("homeUserName").textContent = user.displayName ? user.displayName.split(" ")[0] : "Learner";
  el("dashAvatarSpan").textContent = initials(user.displayName || user.email || "U");
  el("profileAvatar").textContent = initials(user.displayName || user.email || "U");
  el("profileName").textContent = user.displayName || "Learner";
  el("profileEmail").textContent = user.email || "";
  el("profileMemberSince").textContent = formatDate(user.metadata && user.metadata.creationTime);

  boot();
}
init();

async function boot() {
  // Load the generated project index (Website/data/projects.json).
  await refreshProjectList();
  // Poll so newly added project folders appear without a manual reload
  // (scan-projects.js --watch regenerates projects.json on change).
  startAutoRefresh();

  // User profile document (created lazily).
  await loadUserDoc();

  // Realtime progress per user (Firestore — preserved as-is).
  try {
    const progQuery = query(collection(db, "users", currentUser.uid, "progress"));
    onSnapshot(progQuery, (snap) => {
      progressMap = {};
      snap.docs.forEach((d) => {
        progressMap[d.id] = { id: d.id, ...d.data() };
      });
      renderAll();
    });
  } catch (err) {
    console.warn("[LearnJS] Progress listener error:", err.message);
  }
}

/** Fetch the project list and re-render only when it actually changed. */
async function refreshProjectList() {
  try {
    const list = await loadProjects();
    // Include content fields so edits to project.json (description, cover,
    // time, tags) refresh the already-open dashboard too.
    const signature = list.map((p) =>
      [p.id, p.order, p.title, p.description, p.coverImage, p.estimatedTime, (p.tags || []).join(",")].join("|")
    ).join(";");
    if (signature === lastSignature) return;
    lastSignature = signature;
    allProjects = list;
    renderAll();
  } catch (err) {
    console.warn("[LearnJS] Could not load projects:", err.message);
    const loading = el("projectsLoading");
    if (loading) loading.innerHTML = "Could not load projects. Run scan-projects.js and reload.";
  }
}

function startAutoRefresh() {
  setInterval(refreshProjectList, 20000);
  document.addEventListener("visibilitychange", () => {
    if (!document.hidden) refreshProjectList();
  });
}

async function loadUserDoc() {
  const ref = doc(db, "users", currentUser.uid);
  try {
    const snap = await getDoc(ref);
    if (snap.exists()) {
      userDoc = snap.data();
    } else {
      // Lazy-create the profile document.
      const data = {
        uid: currentUser.uid,
        displayName: currentUser.displayName || "",
        email: currentUser.email || "",
        memberSince: serverTimestamp(),
        learningHours: 0,
        currentStreak: 0,
        bestStreak: 0,
        roadmapsCompleted: [],
        createdAt: serverTimestamp()
      };
      await setDoc(ref, data);
      userDoc = data;
    }
    el("profileMemberSince").textContent =
      formatDate((userDoc.memberSince && userDoc.memberSince.toDate && userDoc.memberSince.toDate()) ||
        currentUser.metadata.creationTime);
    el("profileProjects").textContent = "0";
    el("profileRoadmaps").textContent = (userDoc.roadmapsCompleted || []).length;
  } catch (err) {
    console.warn("[LearnJS] User doc load error:", err.message);
  }
}

