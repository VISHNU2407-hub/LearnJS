// Populate category options dynamically from loaded data.
let lastCategories = "";
function refreshCategories() {
  const cats = [...new Set(allProjects.map((p) => p.category).filter(Boolean))].sort();
  const key = cats.join("|");
  if (key === lastCategories) return; // skip needless DOM churn on progress updates
  lastCategories = key;
  const select = el("categoryFilter");
  if (!select) return;
  const current = select.value;
  select.innerHTML = '<option value="all">All Categories</option>' +
    cats.map((c) => '<option value="' + escapeHtml(c) + '">' + escapeHtml(c) + "</option>").join("");
  if ([...select.options].some((o) => o.value === current)) select.value = current;
}

